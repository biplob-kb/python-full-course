import time 
import math
import random

print(time.time())  # Getting the current time in seconds since the epoch
print(time.localtime())  # Getting the local time as a struct_time object

print(math.sqrt(16))  # Calculating the square root of a number
print(math.factorial(5))  # Calculating the factorial of a number
print(math.pi)  # Getting the value of pi
print(math.ceil(4.2))  # Rounding a number up to the nearest integer
print(math.floor(4.8))  # Rounding a number down to the nearest integer
print(math.sin(math.pi / 2))  # Calculating the sine of an angle in radians


print(random.randint(1, 10))  # Generating a random integer between 1 and 10
print(random.choice(['apple', 'banana', 'cherry']))  # Selecting a random element from a list


